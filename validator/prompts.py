def conflicts_prompt(document: str, requirements: list[dict], known: list[str] | None = None) -> str:
    return CONFLICTS_TASK.format(
        requirements=_compact(requirements),
        known=known_block(known or []),
        document=document,
        quote_rules=QUOTE_RULES,
    )


def slice_prompt(document: str) -> str:
    return SLICE_TASK.format(document=document, quote_rules=QUOTE_RULES)


def known_block(known: list[str]) -> str:
    if not known:
        return ""
    lines = "\n".join(f"- {k}" for k in known)
    return (
        "\nУже найдено автоматическими правилами (НЕ повторяй эти дефекты, ищи другие):\n" + lines + "\n"
    )


def requirements_prompt(document: str, requirements: list[dict], known: list[str] | None = None) -> str:
    keys = ", ".join(f'"{k}": "pass"' for k in REQUIREMENT_CRITERIA)
    return REQUIREMENTS_TASK.format(
        criteria=criteria_block(REQUIREMENT_CRITERIA),
        criteria_keys=keys,
        requirements=_compact(requirements),
        known=known_block(known or []),
        document=document,
        quote_rules=QUOTE_RULES,
    )


def set_prompt(document: str, requirements: list[dict], known: list[str] | None = None) -> str:
    return SET_TASK.format(
        criteria=criteria_block(SET_CRITERIA),
        requirements=_compact(requirements),
        known=known_block(known or []),
        document=document,
        quote_rules=QUOTE_RULES,
    )


def _compact(requirements: list[dict]) -> str:
    fields = ("id", "doc_id", "section", "category", "summary", "quote", "line")
    return json.dumps([{k: r.get(k) for k in fields} for r in requirements], ensure_ascii=False, indent=0)
